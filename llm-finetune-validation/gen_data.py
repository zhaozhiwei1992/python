# 身份样本重复份数：身份先验极强（基座对"我是通义千问"置信度很高），
# 8 条身份样本在 92 条数据里占比仅 ~9%，LoRA 梯度被业务长文本稀释，
# 压不过先验（实测 lr 5e-5 训完"你是谁"仍自称 Qwen/通义）。
# 重复 3 份后身份占比 ~30%，配合 lr 1e-4 才能掰正。可调 2-5。
IDENTITY_REPEAT = 3


def build_dataset():
    train, eval_set = [], []

    # 1) 财政 + 系统知识
    for topic, k in KNOWLEDGE.items():
        for q in k["train_questions"]:
            train.append({"instruction": q, "input": "", "output": k["answer"]})
        for q in k["eval_questions"]:
            eval_set.append({"instruction": q, "input": "", "output": k["answer"]})

    # 2) 身份：train 取全部 IDENTITY × IDENTITY_REPEAT（重复增强，掰正强先验）；
    #    eval 取 2 条换问法（保证与训练措辞不同，且与训练集零重复）
    for q, a in IDENTITY:
        for _ in range(IDENTITY_REPEAT):
            train.append({"instruction": q, "input": "", "output": a})
    eval_set.append({"instruction": "你是谁？介绍一下你自己。", "input": "", "output": IDENTITY[3][1]})
    eval_set.append({"instruction": "你被谁开发出来的？", "input": "", "output": IDENTITY[7][1]})

    # 3) 高区分度综合题（训练集中只有各自定义，无整段综合表述）
    eval_set.append({
        "instruction": "财政直接支付和财政授权支付有什么区别？",
        "input": "",
        "output": (
            "财政直接支付和财政授权支付的区别主要在支付指令的签发主体和适用范围："
            "财政直接支付由财政部门向代理银行签发支付指令，通过国库单一账户体系将资金直接"
            "支付到收款人账户，适用于工资支出、政府采购支出、大型工程支出等大额或集中性支出；"
            "财政授权支付由预算单位在财政部门批复的用款额度内自行向代理银行签发支付指令，"
            "通过预算单位零余额账户办理支付，适用于办公费、差旅费、会议费等日常零星支出。"
        ),
    })
    eval_set.append({
        "instruction": "85_一体化系统的支付方式是怎样的？",
        "input": "",
        "output": KNOWLEDGE["85_一体化系统的支付方式"]["answer"],
    })

    return train, eval_set


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-o", "--output", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "data"))
    args = ap.parse_args()
    out = os.path.abspath(args.output)
    os.makedirs(out, exist_ok=True)

    train, eval_set = build_dataset()

    # 校验：验证集问法不得与训练集重复
    train_qs = {t["instruction"] for t in train}
    dup = [e["instruction"] for e in eval_set if e["instruction"] in train_qs]
    assert not dup, f"验证集与训练集存在重复问法: {dup}"

    with open(os.path.join(out, "ascend_finance_train.json"), "w", encoding="utf-8") as f:
        json.dump(train, f, ensure_ascii=False, indent=2)
    with open(os.path.join(out, "ascend_finance_eval.json"), "w", encoding="utf-8") as f:
        json.dump(eval_set, f, ensure_ascii=False, indent=2)

    print(f"train: {len(train)} 条 -> {os.path.join(out, 'ascend_finance_train.json')}")
    print(f"eval : {len(eval_set)} 条 -> {os.path.join(out, 'ascend_finance_eval.json')}")


if __name__ == "__main__":
    main()
